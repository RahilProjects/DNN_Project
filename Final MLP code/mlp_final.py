import numpy as np
import pandas as pd                                    # to read the Excel file
import tensorflow as tf
import matplotlib.pyplot as plt                        # for plotting

from sklearn.model_selection import RepeatedKFold, train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from scipy.stats import gaussian_kde


# -------------------------------------------------
# Input data
# -------------------------------------------------

SEED = 2026                                            # same seed as report/script 04
tf.keras.utils.set_random_seed(SEED)
np.random.seed(SEED)

# Read the ENB2012 dataset directly from UCI repository
url = "https://archive.ics.uci.edu/ml/machine-learning-databases/00242/ENB2012_data.xlsx"
data = pd.read_excel(url).dropna(how="all").iloc[:, :10]

print(data.head())

# 8 input features (X1 to X8) and 2 targets (HL, CL)
X = data.iloc[:, :8].values.astype("float32")
y = data.iloc[:, 8:10].values.astype("float32")

print("\nInput shape:", X.shape)
print("Output shape:", y.shape)

# -------------------------------------------------
# Helper function to build the Best MLP
# -------------------------------------------------

def build_mlp():
    l2_reg = tf.keras.regularizers.l2(1e-4)

    model = tf.keras.models.Sequential([
        # Input layer: 8 features
        tf.keras.layers.Input(shape=(8,)),

        # Hidden layers: 256 -> 128 -> 64 -> 32
        tf.keras.layers.Dense(256, activation='relu', kernel_regularizer=l2_reg),
        tf.keras.layers.Dense(128, activation='relu', kernel_regularizer=l2_reg),
        tf.keras.layers.Dense(64,  activation='relu', kernel_regularizer=l2_reg),
        tf.keras.layers.Dense(32,  activation='relu', kernel_regularizer=l2_reg),

        # Output layer: 2 linear neurons (HL, CL)
        tf.keras.layers.Dense(2, activation='linear')
    ])

    model.compile(
        optimizer=tf.keras.optimizers.Adam(learning_rate=0.003),
        loss='mse',
        metrics=['mae']
    )
    return model


# -------------------------------------------------
# Repeated 10-Fold Cross-Validation (10 folds x 3 repeats = 30 folds)
# -------------------------------------------------

N_SPLITS = 10
N_REPEATS = 3

rkf = RepeatedKFold(n_splits=N_SPLITS, n_repeats=N_REPEATS, random_state=SEED)

hl_mae_list, cl_mae_list = [], []
hl_r2_list,  cl_r2_list  = [], []
all_y_true,  all_y_pred  = [], []

for fold, (train_idx, test_idx) in enumerate(rkf.split(X)):
    tf.keras.backend.clear_session()
    tf.keras.utils.set_random_seed(SEED + fold)

    # Split fold data
    X_train, X_test = X[train_idx], X[test_idx]
    y_train, y_test = y[train_idx], y[test_idx]

    # Standardize inputs and targets (fit on training fold ONLY to prevent leakage)
    scaler_X = StandardScaler()
    X_train_s = scaler_X.fit_transform(X_train)
    X_test_s  = scaler_X.transform(X_test)

    scaler_y = StandardScaler()
    y_train_s = scaler_y.fit_transform(y_train)

    # Inner 15% validation split for EarlyStopping
    X_tr, X_val, y_tr, y_val = train_test_split(
        X_train_s, y_train_s, test_size=0.15, random_state=SEED + fold
    )

    # Build and train MLP
    model = build_mlp()

    callbacks = [
        tf.keras.callbacks.EarlyStopping(
            monitor='val_loss', patience=30, restore_best_weights=True
        ),
        tf.keras.callbacks.ReduceLROnPlateau(
            monitor='val_loss', factor=0.5, patience=15, min_lr=1e-5
        )
    ]

    history = model.fit(
        X_tr, y_tr,
        validation_data=(X_val, y_val),
        epochs=300,
        batch_size=32,
        callbacks=callbacks,
        verbose=0
    )

    # Predict and convert back to original kWh/m^2 units
    y_pred_s = model.predict(X_test_s, verbose=0)
    y_pred = scaler_y.inverse_transform(y_pred_s)

    # Save fold metrics
    hl_mae_list.append(mean_absolute_error(y_test[:, 0], y_pred[:, 0]))
    cl_mae_list.append(mean_absolute_error(y_test[:, 1], y_pred[:, 1]))
    hl_r2_list.append(r2_score(y_test[:, 0], y_pred[:, 0]))
    cl_r2_list.append(r2_score(y_test[:, 1], y_pred[:, 1]))

    all_y_true.append(y_test)
    all_y_pred.append(y_pred)

    if (fold + 1) % 5 == 0 or (fold + 1) == (N_SPLITS * N_REPEATS):
        print(f"Completed fold {fold + 1}/{N_SPLITS * N_REPEATS}")


# -------------------------------------------------
# Print Final 10-Fold x 3 Summary (Matches Report Table II)
# -------------------------------------------------

print("\n=== Final MLP Results (10-Fold CV x 3, 30 folds) ===")
print(f"Heating Load (HL) | MAE: {np.mean(hl_mae_list):.3f} ± {np.std(hl_mae_list):.3f} kWh/m^2 | R2: {np.mean(hl_r2_list):.4f}")
print(f"Cooling Load (CL) | MAE: {np.mean(cl_mae_list):.3f} ± {np.std(cl_mae_list):.3f} kWh/m^2 | R2: {np.mean(cl_r2_list):.4f}")

# -------------------------------------------------
# Training vs Validation Loss (Last Fold)
# -------------------------------------------------

plt.plot(history.history['loss'], label='Training Loss')
plt.plot(history.history['val_loss'], label='Validation Loss')
plt.xlabel('Epoch')
plt.ylabel('MSE Loss (Scaled)')
plt.title('Training vs Validation Loss (Last Fold)')
plt.legend()
plt.grid(alpha=0.3)
plt.show()


# -------------------------------------------------
# 3-Panel Regression Diagnostic Plots (Out-of-Fold Predictions)
# -------------------------------------------------

y_true_all = np.vstack(all_y_true)
y_pred_all = np.vstack(all_y_pred)

for i, name in enumerate(['Heating Load (HL)', 'Cooling Load (CL)']):
    actual = y_true_all[:, i]
    pred = y_pred_all[:, i]
    residuals = actual - pred

    mae = mean_absolute_error(actual, pred)
    rmse = np.sqrt(mean_squared_error(actual, pred))
    r2 = r2_score(actual, pred)

    fig, axes = plt.subplots(1, 3, figsize=(16, 4.5))

    # (a) Actual vs. Predicted
    axes[0].scatter(actual, pred, alpha=0.25, s=12, label=f'Out-of-Fold Samples (n={len(actual)})')
    lims = [min(actual.min(), pred.min()), max(actual.max(), pred.max())]
    axes[0].plot(lims, lims, 'r--', lw=1.8, label='Ideal Parity (y = x)')
    axes[0].text(
        0.05, 0.95,
        f"$R^2$ = {r2:.4f}\nRMSE = {rmse:.3f}\nMAE = {mae:.3f}",
        transform=axes[0].transAxes,
        verticalalignment='top',
        bbox=dict(boxstyle='round', facecolor='white', alpha=0.8)
    )
    axes[0].set_title(f'(a) Actual vs. Predicted {name}')
    axes[0].set_xlabel(f'Actual {name} (kWh/m²)')
    axes[0].set_ylabel(f'Predicted {name} (kWh/m²)')
    axes[0].legend(loc='lower right')
    axes[0].grid(alpha=0.3)

    # (b) Residual Errors vs. Predicted
    axes[1].scatter(pred, residuals, color='green', alpha=0.25, s=12)
    axes[1].axhline(0, color='red', linestyle='--', lw=1.5, label='Zero Error Line')
    axes[1].axhline(2 * rmse, color='gray', linestyle=':', lw=1.2, label=f'±2 RMSE (±{2*rmse:.2f})')
    axes[1].axhline(-2 * rmse, color='gray', linestyle=':', lw=1.2)
    axes[1].set_title(f'(b) Residual Errors vs. Predicted {name}')
    axes[1].set_xlabel(f'Predicted {name} (kWh/m²)')
    axes[1].set_ylabel('Residual Error (Actual - Predicted)')
    axes[1].legend(loc='upper right')
    axes[1].grid(alpha=0.3)

    # (c) Residual Error Distribution
    axes[2].hist(residuals, bins=35, color='mediumpurple', edgecolor='black', alpha=0.65)
    kde_x = np.linspace(residuals.min(), residuals.max(), 200)
    kde = gaussian_kde(residuals)
    bin_width = (residuals.max() - residuals.min()) / 35
    axes[2].plot(kde_x, kde(kde_x) * len(residuals) * bin_width, color='rebeccapurple', lw=1.8)
    axes[2].axvline(0, color='red', linestyle='--', lw=1.5, label='Zero Error')
    axes[2].axvline(residuals.mean(), color='black', linestyle='-.', lw=1.5, label=f'Mean = {residuals.mean():.3f}')
    axes[2].set_title(f'(c) Residual Error Distribution ({name})')
    axes[2].set_xlabel('Residual Error (kWh/m²)')
    axes[2].set_ylabel('Frequency')
    axes[2].legend(loc='upper right')
    axes[2].grid(alpha=0.3)

    plt.tight_layout()
    plt.show()