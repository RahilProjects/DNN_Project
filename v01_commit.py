import numpy as np
import pandas as pd   # to read the data
import tensorflow as tf
import matplotlib.pyplot as plt     # for plotting

from sklearn.model_selection import train_test_split    # for preparing dataset
from sklearn.preprocessing import StandardScaler


# -------------------------------------------------
# Input data
# -------------------------------------------------

tf.keras.utils.set_random_seed(42)            # random seed for reproducibility

# Read the Excel file directly from the UCI repository
url = 'https://archive.ics.uci.edu/ml/machine-learning-databases/00242/ENB2012_data.xlsx'
data = pd.read_excel(url)

# Rename columns for easier access
data.columns = ['X1_Compactness', 'X2_SurfaceArea', 'X3_WallArea', 'X4_RoofArea', 
                'X5_Height', 'X6_Orientation', 'X7_GlazingArea', 'X8_GlazingDist', 
                'y1_HeatingLoad', 'y2_CoolingLoad']

print(data.head())

# 8 geometric input features
X = data[[
    'X1_Compactness',
    'X2_SurfaceArea',
    'X3_WallArea',
    'X4_RoofArea',
    'X5_Height',
    'X6_Orientation',
    'X7_GlazingArea',
    'X8_GlazingDist'
]].values


# -------------------------------------------------
# Output targets (Multi-Target Regression)
# -------------------------------------------------

# 2 continuous thermodynamic outputs
y = data[[
    'y1_HeatingLoad', 
    'y2_CoolingLoad'
]].values

print("\nInput shape:", X.shape)
print("Output shape:", y.shape)


# -------------------------------------------------
# Train-test split
# -------------------------------------------------

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,      # 80/20 split is standard for 768 samples
    random_state=42
    # Note: 'stratify' is removed because it is only for classification, not continuous regression
)


# -------------------------------------------------
# Standardize input data
# -------------------------------------------------

scaler = StandardScaler()

X_train = scaler.fit_transform(X_train)
X_test = scaler.transform(X_test)

tf.keras.utils.set_random_seed(42)


# -------------------------------------------------
# Neural Network (Multi-Layer Perceptron)
# -------------------------------------------------

model = tf.keras.models.Sequential([

    # Input layer: 8 inputs
    tf.keras.layers.Input(shape=(8,)),

    # Hidden layer 1: 64 neurons (ReLU handles non-linear thermodynamics)
    tf.keras.layers.Dense(64, activation='relu'),

    # Hidden layer 2: 32 neurons
    tf.keras.layers.Dense(32, activation='relu'),

    # Output layer: 2 neurons (Linear activation for continuous regression)
    tf.keras.layers.Dense(2, activation='linear')
])

model.summary()


# -------------------------------------------------
# Compile Neural Network
# -------------------------------------------------

model.compile(

    optimizer=tf.keras.optimizers.Adam(
        learning_rate=0.001
    ),
    
    # MSE is the standard loss function for training regression models
    loss='mean_squared_error',
    
    # MAE is tracked to directly compare with the 2012 Random Forest baseline
    metrics=['mean_absolute_error']
)


# -------------------------------------------------
# Train Neural Network
# -------------------------------------------------

history = model.fit(

    X_train,
    y_train,

    epochs=150,

    batch_size=32,

    validation_split=0.2
)


# -------------------------------------------------
# Test Neural Network
# -------------------------------------------------

test_loss, test_mae = model.evaluate(
    X_test,
    y_test
)

print(f"\nOverall Test MAE: {test_mae:.4f}")


# -------------------------------------------------
# Prediction & Separate Target Evaluation
# -------------------------------------------------

# Predict on the test set
y_pred = model.predict(X_test)

# Calculate MAE for Heating Load (y1) and Cooling Load (y2) separately 
# to benchmark against the Tsanas paper (0.51 HL and 1.42 CL)
mae_heating = np.mean(np.abs(y_test[:, 0] - y_pred[:, 0]))
mae_cooling = np.mean(np.abs(y_test[:, 1] - y_pred[:, 1]))

print(f"\nHeating Load (HL) MAE: {mae_heating:.4f}")
print(f"Cooling Load (CL) MAE: {mae_cooling:.4f}")


# -------------------------------------------------
# Training MAE Plot
# -------------------------------------------------

plt.figure(figsize=(8, 5))
plt.plot(
    history.history['mean_absolute_error'],
    label='Training MAE'
)

plt.plot(
    history.history['val_mean_absolute_error'],
    label='Validation MAE'
)

plt.title('Model Mean Absolute Error')
plt.xlabel('Epoch')
plt.ylabel('MAE')
plt.legend()
plt.show()


# -------------------------------------------------
# Training Loss Plot
# -------------------------------------------------

plt.figure(figsize=(8, 5))
plt.plot(
    history.history['loss'],
    label='Training Loss (MSE)'
)

plt.plot(
    history.history['val_loss'],
    label='Validation Loss (MSE)'
)

plt.title('Model Loss')
plt.xlabel('Epoch')
plt.ylabel('Loss (MSE)')
plt.legend()
plt.show()
